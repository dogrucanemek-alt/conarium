// Every code point below U+3000 and every 37th above, surrogates left out.
const SAMPLE = (() => {
  const out: string[] = []
  for (let cp = 0; cp < 0x110000; cp += cp < 0x3000 ? 1 : 37) {
    if (cp >= 0xd800 && cp < 0xe000) continue
    out.push(String.fromCodePoint(cp))
  }
  return out.join('')
})()

